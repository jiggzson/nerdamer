import { gcd } from '../../src/algebra/gcd/gcd';

import type { Expression } from '../../src/core/classes/expression/Expression';

describe('GCD', () => {
	const check = (input: Expression, expected: string) => {
		expect(input.text()).toEqual(expected);
	};

	it('gcd(0, 0)', () => {
		check(gcd('0', '0'), '0');
	});

	it('gcd(0, 12*x^4-9*x^2+3*x)', () => {
		check(gcd('0', '12*x^4-9*x^2+3*x'), '3*x*(1+x)*((-1+2*x)^2)');
	});

	it('gcd(6*x^3-9*x, 0)', () => {
		check(gcd('6*x^3-9*x', '0'), '3*x*(-3+2*x^2)');
	});

	it('gcd(x^5-3*x+7, 1)', () => {
		check(gcd('x^5-3*x+7', '1'), '1');
	});

	it('gcd(x^5-3*x+7, -1)', () => {
		check(gcd('x^5-3*x+7', '-1'), '1');
	});

	it('gcd(6*x^4+3*x^2, 9)', () => {
		check(gcd('6*x^4+3*x^2', '9'), '3');
	});

	it('gcd(12*x^4-9*x^2+3*x, 12*x^4-9*x^2+3*x)', () => {
		check(gcd('12*x^4-9*x^2+3*x', '12*x^4-9*x^2+3*x'), 'x*(3-9*x+12*x^3)');
	});

	it('gcd(x^6-1, -(x^6-1))', () => {
		check(gcd('x^6-1', '-(x^6-1)'), '-1+x^6');
	});

	it('gcd(6*x^3+12*x^2+6*x, 9*x^2+18*x+9)', () => {
		check(gcd('6*x^3+12*x^2+6*x', '9*x^2+18*x+9'), '3+6*x+3*x^2');
	});

	it('gcd(6*(x-1)*(x+2), 15*(x-1)*(x^3+1))', () => {
		check(gcd('6*(x-1)*(x+2)', '15*(x-1)*(x^3+1)'), '-3+3*x');
	});

	it('gcd(-(x^4-1), x^2-1)', () => {
		check(gcd('-(x^4-1)', 'x^2-1'), '-1+x^2');
	});

	it('gcd((x-2)*(x^4+1), (x-2)*(x^3+3*x+1))', () => {
		check(gcd('(x-2)*(x^4+1)', '(x-2)*(x^3+3*x+1)'), '-2+x');
	});

	it('gcd((x+1)^2*(x^2+3), (x+1)^3*(x-5))', () => {
		check(gcd('(x+1)^2*(x^2+3)', '(x+1)^3*(x-5)'), '1+2*x+x^2');
	});

	it('gcd(x^7+3*x^3-2*x+5, x^6-x^2+4)', () => {
		check(gcd('x^7+3*x^3-2*x+5', 'x^6-x^2+4'), '1');
	});

	it('gcd((x^2+1)*(x^3+2), (x^2+1)*(x^5-7))', () => {
		check(gcd('(x^2+1)*(x^3+2)', '(x^2+1)*(x^5-7)'), '1+x^2');
	});

	it('gcd((x^2+x+1)*(x^4+2), (x^2+x+1)*(x^3-3))', () => {
		check(gcd('(x^2+x+1)*(x^4+2)', '(x^2+x+1)*(x^3-3)'), '1+x+x^2');
	});

	it('gcd(x^12-1, x^8-1)', () => {
		check(gcd('x^12-1', 'x^8-1'), '-1+x^4');
	});

	it('gcd(x^6-1, x^3+1)', () => {
		check(gcd('x^6-1', 'x^3+1'), '1+x^3');
	});

	it('gcd(x^6+1, x^4+1)', () => {
		check(gcd('x^6+1', 'x^4+1'), '1');
	});

	it('gcd(x^5-1, x^5+1)', () => {
		check(gcd('x^5-1', 'x^5+1'), '1');
	});

	it('gcd((x-1)^7, (x-1)^4)', () => {
		check(gcd('(x-1)^7', '(x-1)^4'), '1-4*x+6*x^2-4*x^3+x^4');
	});

	it('gcd((3/2)*x^4-(9/4)*x^2, (6/5)*x^3-(18/10)*x)', () => {
		check(gcd('(3/2)*x^4-(9/4)*x^2', '(6/5)*x^3-(18/10)*x'), 'x*(-9+6*x^2)');
	});

	it('gcd((7/3)*(x^3-2*x+1), (14/9)*(x^2+1)*(x^3-2*x+1))', () => {
		check(gcd('(7/3)*(x^3-2*x+1)', '(14/9)*(x^2+1)*(x^3-2*x+1)'), '(1/3)*(7-14*x+7*x^3)');
	});

	it('gcd((x-a)*(x^2+1), (x-a)*(x^3+b))', () => {
		check(gcd('(x-a)*(x^2+1)', '(x-a)*(x^3+b)'), 'a-x');
	});

	it('gcd((x^2+a)*(x^3+1), (x^2+a)*(x^4+b*x+1))', () => {
		check(gcd('(x^2+a)*(x^3+1)', '(x^2+a)*(x^4+b*x+1)'), 'x^2+a');
	});

	it('gcd(x^2+a*x+1, x^2+(a+1)*x+1)', () => {
		check(gcd('x^2+a*x+1', 'x^2+(a+1)*x+1'), '1');
	});

	it('gcd(x^4-2*x^3+x^2, x^3-x^2)', () => {
		check(gcd('x^4-2*x^3+x^2', 'x^3-x^2'), 'x^2*(-1+x)');
	});

	it('gcd((x^2-1)^3*(x+2), (x^2-1)^2*(x^5+1))', () => {
		check(gcd('(x^2-1)^3*(x+2)', '(x^2-1)^2*(x^5+1)'), '1+x-2*x^2-2*x^3+x^4+x^5');
	});

	it('gcd(0, 0)', () => {
		check(gcd('0', '0'), '0');
	});

	it('gcd(0, 6*x^2*y-12*x*y^2+18)', () => {
		check(gcd('0', '6*x^2*y-12*x*y^2+18'), '6*(x^2*y-2*x*y^2+3)');
	});

	it('gcd(x^2+y^2+1, 1)', () => {
		check(gcd('x^2+y^2+1', '1'), '1');
	});

	it('gcd((x+y)^3*(x-1), (x+y)^3*(x-1))', () => {
		check(
			gcd('(x+y)^3*(x-1)', '(x+y)^3*(x-1)'),
			'-y^3-3*x*y^2+x*y^3-3*x^2*y+3*x^2*y^2-x^3+x^4+3*x^3*y'
		);
	});

	it('gcd((x^2+y^2-1), -(x^2+y^2-1))', () => {
		check(gcd('(x^2+y^2-1)', '-(x^2+y^2-1)'), '-1+y^2+x^2');
	});

	it('gcd(x*y*(x+y+1), x*y*(x^2-y+3))', () => {
		check(gcd('x*y*(x+y+1)', 'x*y*(x^2-y+3)'), 'x*y');
	});

	it('gcd(x^2*y^3*(x+1), x^2*y^3*(y+2))', () => {
		check(gcd('x^2*y^3*(x+1)', 'x^2*y^3*(y+2)'), 'x^2*y^3');
	});

	it('gcd((x+y)*(x^2+1), (x+y)*(y^2+3))', () => {
		check(gcd('(x+y)*(x^2+1)', '(x+y)*(y^2+3)'), 'y+x');
	});

	it('gcd((x-y)*(x+y)*(x+1), (x-y)*(x^2+y^2+1))', () => {
		check(gcd('(x-y)*(x+y)*(x+1)', '(x-y)*(x^2+y^2+1)'), '-y+x');
	});

	it('gcd((x^2+y^2)*(x+1), (x^2+y^2)*(x-y+3))', () => {
		check(gcd('(x^2+y^2)*(x+1)', '(x^2+y^2)*(x-y+3)'), 'x^2+y^2');
	});

	it('gcd((x^2+y^2+1)*(x+y), (x^2+y^2+1)*(x^2+2))', () => {
		check(gcd('(x^2+y^2+1)*(x+y)', '(x^2+y^2+1)*(x^2+2)'), '1+y^2+x^2');
	});

	it('gcd((x+y)^5, (x+y)^2*(x-y))', () => {
		check(gcd('(x+y)^5', '(x+y)^2*(x-y)'), 'y^2+2*x*y+x^2');
	});

	it('gcd((x^2+y)^3*(x+1), (x^2+y)^4*(y+1))', () => {
		check(gcd('(x^2+y)^3*(x+1)', '(x^2+y)^4*(y+1)'), 'y^3+3*x^2*y^2+3*x^4*y+x^6');
	});

	it('gcd(x^2+2*x*y+y^2, x^3+3*x^2*y+3*x*y^2+y^3)', () => {
		check(gcd('x^2+2*x*y+y^2', 'x^3+3*x^2*y+3*x*y^2+y^3'), 'y^2+2*x*y+x^2');
	});

	it('gcd(x^2-2*x*y+y^2, x^3-3*x^2*y+3*x*y^2-y^3)', () => {
		check(gcd('x^2-2*x*y+y^2', 'x^3-3*x^2*y+3*x*y^2-y^3'), 'y^2-2*x*y+x^2');
	});

	it('gcd((x-a)*(y+1), (x-a)*(y^2+b))', () => {
		check(gcd('(x-a)*(y+1)', '(x-a)*(y^2+b)'), 'a-x');
	});

	it('gcd((x^2+a*y)*(x+y), (x^2+a*y)*(x-y+1))', () => {
		check(gcd('(x^2+a*y)*(x+y)', '(x^2+a*y)*(x-y+1)'), 'x^2+a*y');
	});

	it('gcd(x^2+a*x*y+b, x^2+(a+1)*x*y+b)', () => {
		check(gcd('x^2+a*x*y+b', 'x^2+(a+1)*x*y+b'), '1');
	});

	it('gcd((x^3-1)*(y+2), (x^2-1)*(x^3-1)*(y^2+1))', () => {
		check(gcd('(x^3-1)*(y+2)', '(x^2-1)*(x^3-1)*(y^2+1)'), '-1+x^3');
	});

	it('gcd((y^3-1)*(x+2), (y^3-1)*(x^2+1))', () => {
		check(gcd('(y^3-1)*(x+2)', '(y^3-1)*(x^2+1)'), '(1+y+y^2)*(-1+y)');
	});

	it('gcd((x*y-1)*(x+1), (x*y-1)*(y+1))', () => {
		check(gcd('(x*y-1)*(x+1)', '(x*y-1)*(y+1)'), '-1+x*y');
	});

	it('gcd((x+y+z)*(x^2+1), (x+y+z)*(y^2+z^2+1))', () => {
		check(gcd('(x+y+z)*(x^2+1)', '(x+y+z)*(y^2+z^2+1)'), 'z+y+x');
	});

	it('gcd(x*y*z*(x+z), x*y*z*(y+1))', () => {
		check(gcd('x*y*z*(x+z)', 'x*y*z*(y+1)'), 'x*y*z');
	});

	it('gcd((x-y)^3*(z+1), (x-y)*(x+z))', () => {
		check(gcd('(x-y)^3*(z+1)', '(x-y)*(x+z)'), '-y+x');
	});

	it('gcd(6*(x+y)*(x-1), 15*(x+y)*(y+2))', () => {
		check(gcd('6*(x+y)*(x-1)', '15*(x+y)*(y+2)'), '3*y+3*x');
	});

	it('gcd(x^2*y + x*y^2 + x^2 + x*y, x*y + y^2 + x + y)', () => {
		check(gcd('x^2*y + x*y^2 + x^2 + x*y', 'x*y + y^2 + x + y'), 'y+x');
	});

	it('gcd((x+y+z)^2 - (x^2+y^2+z^2), (x+y+z)^3 - (x^3+y^3+z^3))', () => {
		check(gcd('(x+y+z)^2 - (x^2+y^2+z^2)', '(x+y+z)^3 - (x^3+y^3+z^3)'), '1');
	});

	it('[slow] gcd(-a*b^11*x^2+a^12*x^2-b^12*x+a^11*b*x-b^11*c+a^11*c, -a*b^12*x^4+a^12*b*x^4+b^14*x-b^11*x-a^11*b^3*x+a^11*x)', () => {
		check(
			gcd(
				'-a*b^11*x^2+a^12*x^2-b^12*x+a^11*b*x-b^11*c+a^11*c',
				'-a*b^12*x^4+a^12*b*x^4+b^14*x-b^11*x-a^11*b^3*x+a^11*x'
			),
			'-b^11+a^11'
		);
	});

	it('gcd(3*a^2*b*x^3-a*b*x^3-3*a*b^2*x+b^2*x, a*x^2*y-b*y+a*x^3-b*x)', () => {
		check(gcd('3*a^2*b*x^3-a*b*x^3-3*a*b^2*x+b^2*x', 'a*x^2*y-b*y+a*x^3-b*x'), '1');
	});

	it('gcd(44*x^2*y^4+12*x^4*y^3+20*x^2*y^3-22*x*y^2-6*x^3*y-10*x*y+11*y+3*x^2+5, -4*x^2*y^4+20*x^3*y^3+2*x*y^2-10*x^2*y-y+5*x)', () => {
		check(
			gcd(
				'44*x^2*y^4+12*x^4*y^3+20*x^2*y^3-22*x*y^2-6*x^3*y-10*x*y+11*y+3*x^2+5',
				'-4*x^2*y^4+20*x^3*y^3+2*x*y^2-10*x^2*y-y+5*x'
			),
			'1-2*x*y+4*x^2*y^3'
		);
	});

	it('gcd(121*a^3*b^4+121*a^2*b^4-121*a^4*b^3-121*a^3*b^3+11*a*b^3-11*a^3*b^2-22*a^2*b^2-a*b, 11*a*b^8-11*a^2*b^7-a*b^6+121*a^3*b^4+121*a^2*b^4-121*a^4*b^3-121*a^3*b^3-11*a^2*b^2-11*a^4*b-a^3)', () => {
		check(
			gcd(
				'121*a^3*b^4+121*a^2*b^4-121*a^4*b^3-121*a^3*b^3+11*a*b^3-11*a^3*b^2-22*a^2*b^2-a*b',
				'11*a*b^8-11*a^2*b^7-a*b^6+121*a^3*b^4+121*a^2*b^4-121*a^4*b^3-121*a^3*b^3-11*a^2*b^2-11*a^4*b-a^3'
			),
			'a*(1-11*b^2+11*a*b)'
		);
	});

	it('gcd(-a*b^3*x^2+a^4*x^2-b^4*x+a^3*b*x-b^3*c+a^3*c, -a*b^4*x^4+a^4*b*x^4+b^6*x-a^3*b^3*x-b^3*x+a^3*x)', () => {
		check(
			gcd(
				'-a*b^3*x^2+a^4*x^2-b^4*x+a^3*b*x-b^3*c+a^3*c',
				'-a*b^4*x^4+a^4*b*x^4+b^6*x-a^3*b^3*x-b^3*x+a^3*x'
			),
			'-b^3+a^3'
		);
	});

	it('gcd(-x^3*y^2-x*y^2+5*x^5*y+8*x^3*y+x*y-10*x^5-2*x^3, 2*x^2*y^2+2*y^2-x^3*y-4*x^2*y-x*y+2*x^3)', () => {
		check(
			gcd(
				'-x^3*y^2-x*y^2+5*x^5*y+8*x^3*y+x*y-10*x^5-2*x^3',
				'2*x^2*y^2+2*y^2-x^3*y-4*x^2*y-x*y+2*x^3'
			),
			'y-2*x^2+x^2*y'
		);
	});

	it('gcd(a^2*x^3+a*x^3-a^3*x^2-a^2*x^2+x-a, a^2*x^4+a*x^4+2*a^2*x^3+2*a*x^3+6*a^2*x^2+6*a*x^2+x^2+2*x+6)', () => {
		check(
			gcd(
				'a^2*x^3+a*x^3-a^3*x^2-a^2*x^2+x-a',
				'a^2*x^4+a*x^4+2*a^2*x^3+2*a*x^3+6*a^2*x^2+6*a*x^2+x^2+2*x+6'
			),
			'1+a*x^2+a^2*x^2'
		);
	});

	it('gcd(-2*y*z-2*x*z-2*z+x*y^2+x^2*y+x*y, -6*z^2+3*x*y*z+2*y*z-2*x*z-x*y^2+x^2*y)', () => {
		check(
			gcd('-2*y*z-2*x*z-2*z+x*y^2+x^2*y+x*y', '-6*z^2+3*x*y*z+2*y*z-2*x*z-x*y^2+x^2*y'),
			'-2*z+x*y'
		);
	});

	it('gcd(b*x^2-3*b^2*x+a*b*x+a^2*x-3*a^2*b+a^3, -b*x^3-a^2*x^2+b^2*x+2*a*b*x+a^2*b+2*a^3)', () => {
		check(
			gcd(
				'b*x^2-3*b^2*x+a*b*x+a^2*x-3*a^2*b+a^3',
				'-b*x^3-a^2*x^2+b^2*x+2*a*b*x+a^2*b+2*a^3'
			),
			'a^2+b*x'
		);
	});

	it('gcd(6*w^2+2*u^2*v*w-3*v*w+3*u*w-u^2*v^2+u^3*v, 3*w^2+u^2*v*w+3*u*v*w-15*w+u^3*v^2-5*u^2*v)', () => {
		check(
			gcd(
				'6*w^2+2*u^2*v*w-3*v*w+3*u*w-u^2*v^2+u^3*v',
				'3*w^2+u^2*v*w+3*u*v*w-15*w+u^3*v^2-5*u^2*v'
			),
			'3*w+u^2*v'
		);
	});

	it('gcd(-b^11*c+a^11*c-3*b^12-9*a*b^11+3*a^11*b+9*a^12, 3*b^14-81*a*b^12-3*b^11-3*a^11*b^3+81*a^12*b+3*a^11)', () => {
		check(
			gcd(
				'-b^11*c+a^11*c-3*b^12-9*a*b^11+3*a^11*b+9*a^12',
				'3*b^14-81*a*b^12-3*b^11-3*a^11*b^3+81*a^12*b+3*a^11'
			),
			'-b^11+a^11'
		);
	});

	it('gcd(-x^2*y^3-y^3+3*x^4*y^2+3*x^2*y^2-3*x^6*y-3*x^4*y+x^8+x^6, -y^3*z^2+3*x^2*y^2*z^2-3*x^4*y*z^2+x^6*z^2-y^5+3*x^2*y^4-3*x^4*y^3-x^2*y^3+x^6*y^2+3*x^4*y^2-3*x^6*y+x^8)', () => {
		check(
			gcd(
				'-x^2*y^3-y^3+3*x^4*y^2+3*x^2*y^2-3*x^6*y-3*x^4*y+x^8+x^6',
				'-y^3*z^2+3*x^2*y^2*z^2-3*x^4*y*z^2+x^6*z^2-y^5+3*x^2*y^4-3*x^4*y^3-x^2*y^3+x^6*y^2+3*x^4*y^2-3*x^6*y+x^8'
			),
			'-y^3+3*x^2*y^2-3*x^4*y+x^6'
		);
	});
});
