/** Real and imaginary parts of a computed root. */
function parts(root: Expression): [Decimal, Decimal] {
	const value = root.evaluate();
	return [
		new Decimal(value.realPart().text({ decimal: true })),
		new Decimal(value.imagPart().text({ decimal: true })),
	];
}

/** Expects every reference root to match a computed root to `digits` relative digits. */
function expectRoots(roots: Expression[], expected: string[][], digits: number) {
	expect(roots.length).toBe(expected.length);
	const values = roots.map(parts);
	for (const [re, im] of expected) {
		const target = [new Decimal(re), new Decimal(im)];
		const size = target[0].abs().plus(target[1].abs());
		const errors = values.map(([a, b]) =>
			a.minus(target[0]).abs().plus(b.minus(target[1]).abs())
		);
		const error = Decimal.min(...errors);
		const limit = size.isZero()
			? new Decimal('1e-40')
			: size.times(new Decimal(10).pow(-digits));
		expect(error.lte(limit)).toBe(true);
	}
}

